#!/usr/bin/env bash
# PreToolUse hook (see ../settings.json): runs before a Bash call that runs `git commit`
# or `git push`, checks it, and blocks it (exit 2) with a specific reason if something
# is wrong - never fixes anything silently, so the failure message is always the thing
# that tells Claude what to do next.
#
# Policy (commits): no Co-Authored-By trailer, no --no-verify, no unsigned commit.
# Checks: the repository's own pre-commit hooks (.pre-commit-config.yaml, the one place
# they are defined), the stage git would run: pre-commit for a commit, pre-push for a
# push. Skipped when git's own hook for that stage is installed, since git runs it then.
#
# Kept identical across repos; change it everywhere at once.
set -u

if ! command -v jq >/dev/null 2>&1; then
  echo "pre-commit-checks.sh: jq not found, skipping checks" >&2
  exit 0
fi

cmd=$(jq -r '.tool_input.command // empty')

# Flags and subcommands are read from the command without its message: drop any heredoc
# body and quoted strings, so a message (or a script) that merely mentions a command or
# flag is not mistaken for it.
bare=${cmd%%<<*}
bare=$(printf '%s' "$bare" | sed -E "s/'[^']*'//g; s/\"[^\"]*\"//g")

# `git [-C dir | -c key=value]... <subcommand>` at the start of a command or after
# ;, &&, || or |. `git commit-tree`, `git -C . log --grep=commit` and the like never match.
runs() {
  printf '%s' "$bare" |
    grep -qE "(^|[;&|])[[:space:]]*git([[:space:]]+-[cC][[:space:]]+[^[:space:]]+)*[[:space:]]+$1([[:space:]]|$)"
}

if runs commit; then
  stage=pre-commit
elif runs push; then
  stage=pre-push
else
  exit 0
fi

cd "${CLAUDE_PROJECT_DIR:-.}" || exit 0

block() {
  echo "BLOCKED: $1" >&2
  echo >&2
  echo "$2" >&2
  exit 2
}

if [ "$stage" = pre-commit ]; then
  shopt -s nocasematch
  case "$cmd" in
    *"Co-Authored-By"*)
      block "the commit command contains a Co-Authored-By trailer." \
        "Remove the Co-Authored-By line from the commit message, then retry the commit."
      ;;
  esac
  shopt -u nocasematch

  case "$bare" in
    *"--no-gpg-sign"*)
      block "the commit command disables signing (--no-gpg-sign)." \
        "Commits must be signed. Remove --no-gpg-sign and retry."
      ;;
  esac

  case "$bare" in
    *" -S"* | *"--gpg-sign"*) ;;
    *)
      if [ "$(git config --get commit.gpgsign)" != "true" ]; then
        block "the commit would not be signed." \
          "Add -S to the git commit command (commit.gpgsign is not enabled), then retry."
      fi
      ;;
  esac
fi

case "$bare" in
  *"--no-verify"*)
    block "the command uses --no-verify." \
      "Never skip hooks. Fix whatever the hooks report, then retry without --no-verify."
    ;;
esac

[ -f .pre-commit-config.yaml ] || exit 0

# When git's own hook for this stage is pre-commit's, git runs these same checks right
# after this hook, so running them here too would run them twice. Any other hook there
# (absent, or another tool's) means git will not run them: run them here.
# (`--git-path` follows core.hooksPath.)
git_hook=$(git rev-parse --git-path "hooks/$stage" 2>/dev/null)
if [ -x "$git_hook" ] && grep -q "File generated by pre-commit" "$git_hook" 2>/dev/null; then
  exit 0
fi

# Exactly as git's hook would: no file arguments, so pre-commit checks what is staged
# (it stashes unstaged changes meanwhile), not the working tree.
echo "pre-commit-checks.sh: running the $stage hooks" >&2
if ! out=$(uv run pre-commit run --hook-stage "$stage" 2>&1); then
  block "the $stage hooks failed." "$out"
fi

exit 0
